from datetime import datetime
from enum import Enum

from sqlalchemy import JSON, DateTime, ForeignKey, Numeric, String, Text
from sqlalchemy import Enum as SqlEnum
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import TimestampMixin
from app.db.database import Base


class AppealStatus(str, Enum):
    DRAFT = "draft"
    GENERATED = "generated"
    REVIEW = "review"
    APPROVED = "approved"
    SUBMITTED = "submitted"
    ACCEPTED = "accepted"
    REJECTED = "rejected"
    DENIED = "denied"
    WITHDRAWN = "withdrawn"
    CLOSED = "closed"


class Appeal(Base, TimestampMixin):
    """
    An appeal letter generated by Atlas for a denied or underpaid claim.
    Appeals are always created as drafts — a human reviews before submitting.
    """

    __tablename__ = "appeals"

    id: Mapped[int] = mapped_column(primary_key=True)

    organization_id: Mapped[int] = mapped_column(
        ForeignKey("organizations.id"),
        nullable=False,
        index=True,
    )

    claim_id: Mapped[int] = mapped_column(
        ForeignKey("claims.id"),
        nullable=False,
        index=True,
    )

    recovery_case_id: Mapped[int | None] = mapped_column(
        ForeignKey("recovery_cases.id"),
        nullable=True,
    )

    # The structured AI analysis (ClaimAnalysis) this appeal was generated
    # from, if any — lets the appeal's reasoning trace back to root_cause/
    # recommended_action/ai_summary.
    analysis_id: Mapped[int | None] = mapped_column(
        ForeignKey("claim_analyses.id"),
        nullable=True,
    )

    status: Mapped[AppealStatus] = mapped_column(
        SqlEnum(AppealStatus),
        default=AppealStatus.DRAFT,
        nullable=False,
        index=True,
    )

    appeal_text: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    title: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )

    summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # Sectioned appeal — each key is a section name, value is the section text
    sections: Mapped[dict | None] = mapped_column(
        JSON,
        nullable=True,
    )

    citations: Mapped[dict | None] = mapped_column(
        JSON,
        nullable=True,
    )

    # List[str] of recommended attachments the AI suggests accompany the
    # appeal (operative report, itemized bill, etc.) — distinct from
    # `missing_documents` below, which is Atlas' own structural verification.
    attachments: Mapped[list | None] = mapped_column(
        JSON,
        nullable=True,
    )

    # List[str] of things the AI itself flagged as missing/uncertain while
    # reasoning about the appeal (e.g. "exact denial date not provided").
    missing_information: Mapped[list | None] = mapped_column(
        JSON,
        nullable=True,
    )

    # List[str] of documents the denial code's knowledge-base entry says are
    # typically required, that Atlas could NOT structurally verify were on
    # file for this claim (see app.appeals.evidence.EvidenceCollector).
    # Advisory only — Atlas doesn't store clinical attachments, so this is
    # a checklist for the human reviewer, not a hard gate.
    missing_documents: Mapped[list | None] = mapped_column(
        JSON,
        nullable=True,
    )

    required_documents: Mapped[list | None] = mapped_column(
        JSON,
        nullable=True,
    )

    references: Mapped[list | None] = mapped_column(
        JSON,
        nullable=True,
    )

    confidence: Mapped[float | None] = mapped_column(
        Numeric(5, 4),
        nullable=True,
    )

    # Appeal Quality Score — {completeness, evidence, tone, compliance,
    # confidence, overall, flagged_for_review} — see app.appeals.quality.
    quality_score: Mapped[dict | None] = mapped_column(
        JSON,
        nullable=True,
    )

    grounding_report: Mapped[dict | None] = mapped_column(
        JSON,
        nullable=True,
    )

    ai_provider: Mapped[str | None] = mapped_column(
        nullable=True,
    )

    # Who/what produced the current draft ("ai" by default, or a user id
    # once a reviewer has edited it) and who ultimately submitted it.
    generated_by: Mapped[str | None] = mapped_column(
        nullable=True,
        default="ai",
    )

    submitted_by: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"),
        nullable=True,
    )

    approved_by: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"),
        nullable=True,
    )

    approved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    pdf_document_id: Mapped[int | None] = mapped_column(
        ForeignKey("documents.id"),
        nullable=True,
    )

    confirmation_number: Mapped[str | None] = mapped_column(
        nullable=True,
    )

    response_due_date: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Bumped each time update_appeal_text() overwrites the draft — the prior
    # state is snapshotted into AppealVersion first (see appeal_version.py).
    current_version: Mapped[int] = mapped_column(
        default=1,
        nullable=False,
    )

    submitted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    organization = relationship("Organization", back_populates="appeals")
    claim = relationship("Claim", back_populates="appeals")
    analysis = relationship("ClaimAnalysis", back_populates="appeals")
    approver = relationship("User", foreign_keys=[approved_by])
    pdf_document = relationship("Document", foreign_keys=[pdf_document_id])
    versions = relationship(
        "AppealVersion",
        back_populates="appeal",
        cascade="all, delete-orphan",
        order_by="AppealVersion.version_number",
    )

    @property
    def body(self) -> str:
        return self.appeal_text

    @body.setter
    def body(self, value: str) -> None:
        self.appeal_text = value

    @property
    def version(self) -> int:
        return self.current_version
